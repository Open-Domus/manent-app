# Refresh vendor/ from an Omnesis checkout, then apply patches/*.patch.
#
#   scripts/vendor.sh                      # upstream/main + baldarn/omi-assist-commands
#   UPSTREAM_REF=v0.9.0 scripts/vendor.sh  # pin another upstream ref
#
# Modules come whole from UPSTREAM_REF. The voice-command module and the
# shared-audio fan-out, which upstream never took, come from ASSIST_REF.
# Every vendored file stays in its original package, so a refresh is a plain
# overwrite and `git diff vendor/` shows exactly what upstream changed.
set -euo pipefail

FORK="${OMNESIS_FORK:-$HOME/Projects/forks/omnesis}"
UPSTREAM_REF="${UPSTREAM_REF:-upstream/main}"
ASSIST_REF="${ASSIST_REF:-baldarn/omi-assist-commands}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/vendor"

UPSTREAM_MODULES=(core-transport core-pairing core-designsystem feature-recording feature-omi)
ASSIST_MODULES=(feature-assist)
ASSIST_FILES=(
  feature-recording/src/main/kotlin/dev/omnesis/android/feature/recording/SharedWearableAudio.kt
  feature-recording/src/test/kotlin/dev/omnesis/android/feature/recording/SharedWearableAudioTest.kt
)

upstream_sha="$(git -C "$FORK" rev-parse "$UPSTREAM_REF")"
assist_sha="$(git -C "$FORK" rev-parse "$ASSIST_REF")"

extract() { # ref path...
  local ref="$1"; shift
  git -C "$FORK" archive --format=tar "$ref" -- "${@/#/android/}" | tar -x -C "$VENDOR" --strip-components=1
}

for m in "${UPSTREAM_MODULES[@]}" "${ASSIST_MODULES[@]}"; do rm -rf "${VENDOR:?}/$m"; done
mkdir -p "$VENDOR"
extract "$upstream_sha" "${UPSTREAM_MODULES[@]}"
extract "$assist_sha" "${ASSIST_MODULES[@]}" "${ASSIST_FILES[@]}"

# Upstream Omnesis is AGPL-3.0; the copies here are under MIT.
grep -rlZ 'SPDX-License-Identifier: AGPL-3[.]0-or-later' "$VENDOR" "$ROOT/logic-coverage.gradle.kts" \
  | xargs -0 -r sed -i -e 's/SPDX-License-Identifier: AGPL-3[.]0-or-later/SPDX-License-Identifier: MIT/' \
    -e 's|^// Copyright (c) \([0-9]*\) .*|// Copyright (c) \1 Lorenzo Farnararo|'

shopt -s nullglob
for p in "$ROOT"/patches/*.patch; do
  git -C "$ROOT" apply --directory=vendor "$p" || { echo "patch failed: $(basename "$p")" >&2; exit 1; }
done

cat > "$ROOT/VENDORED.md" <<EOF
# Vendored code

Generated by \`scripts/vendor.sh\`; do not edit by hand. Everything under
\`vendor/\` is copied from Omnesis in its original package, with its licence
headers changed to MIT, then \`patches/\` is applied.

| Source | Ref | Commit |
|---|---|---|
| ${UPSTREAM_MODULES[*]} | \`$UPSTREAM_REF\` | \`$upstream_sha\` |
| ${ASSIST_MODULES[*]}, SharedWearableAudio | \`$ASSIST_REF\` | \`$assist_sha\` |

Patches applied:
$(for p in "$ROOT"/patches/*.patch; do echo "- \`$(basename "$p")\`"; done)
EOF
echo "vendored $UPSTREAM_REF@${upstream_sha:0:9} and $ASSIST_REF@${assist_sha:0:9}"
